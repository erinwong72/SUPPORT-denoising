function run_inference(username, root_data, model, support_dirname, background, rerun, run_local, epoch)
% run_inference(..., run_local) — set run_local=true when this MATLAB
% process is already running ON the fanlab server (e.g. via
% preprocessing_headless.m over `matlab -batch` through SSH) so inference.sh
% is invoked directly with system() instead of SSHing back into the same
% machine. Default false (SSH out to the server, for interactive use from a
% local machine).

if nargin < 7
    run_local = false;
end

server_ip = '10.93.5.151'; % fanlab server IP address

inference_script = "/home/" + username + "/SUPPORT-denoising/model/inference.sh";

% convert root data to unix style path
root_data = strrep(root_data, '\', '/');

if run_local
    % already on the server — no SSH hop needed
    clone_cmd = sprintf([ ...
        'if [ ! -d "/home/%s/SUPPORT-denoising" ]; then ' ...
        'git clone https://github.com/erinwong72/SUPPORT-denoising.git /home/%s/SUPPORT-denoising; fi'], ...
        username, username);
    status = system(clone_cmd);
    if status ~= 0
        error('Inference failed for %s, problem setting up repo on server', username);
    end
    fprintf('Running inference locally with model %s and dirname %s\n', model, support_dirname);
    cmd = sprintf('bash %s %s ''%s'' %s %s %d %d %d', ...
        inference_script, ...
        username, ...
        root_data, ...
        model, ...
        support_dirname, ...
        background, ...
        rerun, ...
        epoch);

    system(cmd, '-echo');
    return
end

% first ssh to check if SUPPORT-denoising repo is cloned
cmd = sprintf(['ssh -o StrictHostKeyChecking=no %s@%s ' ...
    '"if [ ! -d \\"/home/%s/SUPPORT-denoising\\" ]; then ' ...
    'git clone https://github.com/erinwong72/SUPPORT-denoising.git /home/%s/SUPPORT-denoising; fi"'], ...
    username, server_ip, username, username);
status = system(cmd);

if status ~= 0
    error('Inference failed for %s, problem setting up repo on server', username);
end

% this might not work if there are spaces in the path
cmd = sprintf([ ...
    'ssh -o StrictHostKeyChecking=no %s@%s ' ...
    '"bash %s %s ''%s'' %s %s %d %d %d"' ], ...
    username, server_ip, ...
    inference_script, ...
    username, ...
    root_data, ...
    model, ...
    support_dirname, ...
    background, ...
    rerun, ...
    epoch);

system(cmd, '-echo');

end
